// Generates supabase/seed.sql from lib/data/seed.ts so both data modes share one source of truth.
// Run with: npm run gen:seed
import { writeFileSync } from "node:fs";
import { SEED_CHARACTERS } from "../lib/data/seed.ts";

const lit = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const arr = (a: string[]) => `array[${a.map(lit).join(", ")}]::text[]`;

const rows = SEED_CHARACTERS.map(
  (c) => `  (${[
    lit(c.id),
    "null",
    lit(c.name),
    lit(c.tagline),
    lit(c.description),
    lit(c.personality),
    arr(c.traits),
    lit(c.background),
    lit(c.greeting),
    lit(c.scenario),
    lit(c.exampleDialogue),
    lit(c.speakingStyle),
    arr(c.tags),
    arr(c.categories),
    lit(c.avatarUrl),
    lit(c.visibility),
    String(c.featured),
    lit(c.createdAt),
  ].join(", ")})`,
);

const sql = `-- Generated by scripts/gen-seed-sql.ts from lib/data/seed.ts. Do not edit by hand.
insert into public.characters (
  id, creator_id, name, tagline, description, personality, traits, background, greeting, scenario,
  example_dialogue, speaking_style, tags, categories, avatar_url, visibility, featured, created_at
) values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name, tagline = excluded.tagline, description = excluded.description,
  personality = excluded.personality, traits = excluded.traits, background = excluded.background,
  greeting = excluded.greeting, scenario = excluded.scenario, example_dialogue = excluded.example_dialogue,
  speaking_style = excluded.speaking_style, tags = excluded.tags, categories = excluded.categories,
  avatar_url = excluded.avatar_url, visibility = excluded.visibility, featured = excluded.featured;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${rows.length} characters`);
